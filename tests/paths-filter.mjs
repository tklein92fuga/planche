const meta={...base,id:'meta',kind:'meta',title:'Meta',parent:'',children:['mixed']};
let resolveProjection;
globalThis.fetch=async url=>({ok:true,json:async()=>url==='/api/paths'?{groups:[base,meta]}:url.startsWith('/api/paths?')?await new Promise(resolve=>{resolveProjection=()=>resolve({groups:[projected,{...meta,members:projected.members,total:3,items:projected.items}]});}):{}});
