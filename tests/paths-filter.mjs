import assert from 'node:assert/strict';
import {readFile} from 'node:fs/promises';
const media='data:text/javascript;base64,'+Buffer.from(await readFile(new URL('../static/media-ui.js',import.meta.url))).toString('base64');
const source=(await readFile(new URL('../static/paths-ui.js',import.meta.url),'utf8')).replace('./media-ui.js',media).replace('./work-hover.js','data:text/javascript,export function createWorkHover(){}');
