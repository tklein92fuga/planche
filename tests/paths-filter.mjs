assert.doesNotMatch(target.innerHTML,/data-path-work=/,'The index displays meta-lists only');
assert.doesNotMatch(target.innerHTML,/media-icon/,'Format icons are removed');
await listeners.click({target:{closest:selector=>selector==='[data-path-list]'?{dataset:{pathList:'meta'}}:null}});
